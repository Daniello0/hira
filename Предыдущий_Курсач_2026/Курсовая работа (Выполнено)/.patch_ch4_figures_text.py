def _set_run_fonts(run) -> None:
    run.font.name = "Times New Roman"
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        from docx.oxml import OxmlElement

        rfonts = OxmlElement("w:rFonts")
        rpr.insert(0, rfonts)
    for k in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
        rfonts.set(qn(k), "Times New Roman")


def _set_paragraph_text(paragraph, new_text: str) -> None:
    """Заменяет текст абзаца, по возможности сохраняя полужирное начертание первого run."""
    bold = None
    size = None
    if paragraph.runs:
        bold = paragraph.runs[0].bold
        size = paragraph.runs[0].font.size
    p = paragraph._element
    for child in list(p):
        if child.tag == qn("w:pPr"):
            continue
        p.remove(child)
    run = paragraph.add_run(new_text)
    _set_run_fonts(run)
    if bold is not None:
        run.bold = bold
    if size is not None:
        run.font.size = size
    if new_text.startswith("Рисунок "):
        run.bold = True
        run.font.size = Pt(13)


