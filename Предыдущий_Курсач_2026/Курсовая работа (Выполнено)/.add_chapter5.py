def _add_page_break(doc) -> None:
    p = _add_paragraph(doc, "По умолчанию")
    run = p.add_run()
    run.add_break(WD_BREAK.PAGE)


def _add_numbered_conclusion(doc, text: str) -> None:
    p = _add_paragraph(doc, "По умолчанию", alignment=WD_ALIGN_PARAGRAPH.JUSTIFY)
    _add_run(p, text)


def _strip_existing_chapter5(doc) -> None:
    body = doc.element.body
    children = list(body.iterchildren())
    start_index = None
    for idx, child in enumerate(children):
        if child.tag == qn("w:p"):
            text = "".join(child.itertext()).strip()
            if text == CH5_TITLE:
                start_index = idx
                break
    if start_index is None:
        return
    for child in children[start_index:]:
        if child.tag == qn("w:sectPr"):
            continue
        body.remove(child)


def _strip_existing_toc_chapter5(doc) -> None:
    to_remove = []
    body = doc.element.body
    for child in body.iterchildren():
        if child.tag != qn("w:p"):
            continue
        text = "".join(child.itertext()).strip()
        if not text:
            continue
        p_pr = child.find(qn("w:pPr"))
        if p_pr is None:
            continue
        p_style = p_pr.find(qn("w:pStyle"))
        if p_style is None:
            continue
        style_val = p_style.get(qn("w:val")) or ""
        if "TOC" not in style_val:
            continue
        if text.startswith("5 ") or text.startswith("5."):
            to_remove.append(child)
    for child in to_remove:
        body.remove(child)


def _insert_toc_chapter5(doc) -> None:
    """Вставляет TOC-записи главы 5 после строки «4.6 Выводы по главе 4»."""
    body = doc.element.body
    anchor = None
    for child in body.iterchildren():
        if child.tag != qn("w:p"):
            continue
        text = "".join(child.itertext()).strip()
        if text.startswith("4.6 Выводы по главе 4"):
            anchor = child
            break
    if anchor is None:
        return
    toc_entries = [
        (1, CH5_TITLE, "32"),
        (2, "5.1 Масштабирование и продуктизация", "32"),
        (2, "5.2 Интеграция с популярными мессенджерами", "33"),
        (2, "5.3 Реализация персонализации", "33"),
        (2, "5.4 Внедрение генеративного слоя для резюмирования вакансий", "34"),
        (
            2,
            "5.5 Усиление слоя извлечения кандидатов (исследовательское направление)",
            "34",
        ),
        (2, "5.6 Выводы по главе 5", "35"),
    ]
    new_paragraphs = []
    for level, text, page in toc_entries:
        p = _build_toc_paragraph(doc, level, text, page)
        new_paragraphs.append(p._element)
        body.remove(p._element)
    insert_after = anchor
    for el in new_paragraphs:
        insert_after.addnext(el)
        insert_after = el


