def _set_run_font(run, name: str = "Times New Roman") -> None:
    run.font.name = name
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.insert(0, rfonts)
    rfonts.set(qn("w:ascii"), name)
    rfonts.set(qn("w:hAnsi"), name)
    rfonts.set(qn("w:eastAsia"), name)
    rfonts.set(qn("w:cs"), name)


def _add_paragraph(doc, style_name: str, alignment=None):
    p = doc.add_paragraph(style=doc.styles[style_name])
    if alignment is not None:
        p.alignment = alignment
    return p


def _add_run(p, text: str, *, bold: bool | None = None, size_pt: int | None = None):
    run = p.add_run(text)
    _set_run_font(run, "Times New Roman")
    if bold is not None:
        run.bold = bold
    if size_pt is not None:
        run.font.size = Pt(size_pt)
    return run


def _add_text_paragraph(doc, text: str, *, style: str = "По умолчанию"):
    p = _add_paragraph(doc, style)
    _add_run(p, text)
    return p


def _add_empty(doc, *, style: str = "По умолчанию"):
    return _add_paragraph(doc, style)


def _add_heading(doc, text: str):
    """Заголовок главы (стиль 'Заголовок')."""
    p = _add_paragraph(doc, "Заголовок")
    _add_run(p, text)
    return p


def _add_subheading(doc, text: str):
    """Подзаголовок параграфа (стиль 'Подзаголовок')."""
    p = _add_paragraph(doc, "Подзаголовок")
    _add_run(p, text)
    return p


def _add_figure(doc, image_path: Path, caption: str, *, width_cm: float = 16.49):
    """Добавляет рисунок с подписью и примечанием по шаблону."""
    img_p = _add_paragraph(doc, "По умолчанию", alignment=WD_ALIGN_PARAGRAPH.CENTER)
    # Сбрасываем отступ первой строки для абзаца с картинкой
    img_p.paragraph_format.first_line_indent = Cm(0)
    img_run = img_p.add_run()
    img_run.add_picture(str(image_path), width=Cm(width_cm))

    cap_p = _add_paragraph(doc, "По умолчанию", alignment=WD_ALIGN_PARAGRAPH.CENTER)
    cap_p.paragraph_format.first_line_indent = Cm(0)
    _add_run(cap_p, caption, bold=True, size_pt=13)

    spacer = _add_paragraph(doc, "По умолчанию", alignment=WD_ALIGN_PARAGRAPH.LEFT)
    spacer.paragraph_format.first_line_indent = Cm(0)

    note_p = _add_paragraph(doc, "По умолчанию", alignment=WD_ALIGN_PARAGRAPH.CENTER)
