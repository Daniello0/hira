def _build_toc_paragraph(doc, level: int, text: str, page: str) -> None:
    """Создаёт абзац оглавления уровня TOC level (1 или 2)."""
    style_name = "TOC 1" if level == 1 else "TOC 2"
    p = doc.add_paragraph(style=doc.styles[style_name])
    run_text = _add_run(p, text)
    # Табуляция и страница (как в исходных TOC-записях)
    tab_run = p.add_run("\t")
    _set_run_font(tab_run, "Times New Roman")
    page_run = _add_run(p, page)
    return p


def _insert_toc_chapter4(doc) -> None:
    """Вставляет TOC-записи главы 4 после '3.8 Выводы по главе 3'."""
    body = doc.element.body
    # Найдём абзац '3.8 Выводы по главе 3'
    anchor = None
    for child in body.iterchildren():
        if child.tag != qn("w:p"):
            continue
        text = "".join(child.itertext()).strip()
        if text.startswith("3.8 Выводы по главе 3"):
            anchor = child
            break
    if anchor is None:
        return
    # Создадим временные TOC-абзацы (в конце документа, потом перенесём)
    toc_entries = [
        (1, "4 ЭКСПЕРИМЕНТАЛЬНАЯ ПРОВЕРКА РАБОТОСПОСОБНОСТИ ЧАТ-БОТА", "20"),
        (2, "4.1 Постановка эксперимента и набор бенчмарков", "20"),
        (2, "4.2 Функциональное тестирование чат-бота в пользовательских сценариях", "21"),
        (2, "4.3 Количественная оценка качества поиска", "24"),
        (2, "4.4 Анализ устойчивости системы и обработка ошибочных запросов", "25"),
        (2, "4.5 Визуализация процесса обработки запроса", "26"),
        (2, "4.6 Выводы по главе 4", "27"),
    ]
    new_paragraphs = []
    for level, text, page in toc_entries:
        p = _build_toc_paragraph(doc, level, text, page)
        new_paragraphs.append(p._element)
        body.remove(p._element)
    # Вставляем в правильное место (после anchor)
    insert_after = anchor
    for el in new_paragraphs:
        insert_after.addnext(el)
        insert_after = el


