CH4_TITLE = "4 ЭКСПЕРИМЕНТАЛЬНАЯ ПРОВЕРКА РАБОТОСПОСОБНОСТИ ЧАТ-БОТА"


def _strip_existing_chapter4(doc) -> None:
    body = doc.element.body
    children = list(body.iterchildren())
    start_index = None
    for idx, child in enumerate(children):
        if child.tag == qn("w:p"):
            text = "".join(child.itertext()).strip()
            if text == CH4_TITLE:
                start_index = idx
                break
    if start_index is None:
        return
    # Удаляем все элементы, начиная со start_index, кроме завершающего sectPr
    for child in children[start_index:]:
        if child.tag == qn("w:sectPr"):
            continue
        body.remove(child)


def _strip_existing_toc_chapter4(doc) -> None:
    """Удаляет TOC-записи 4 ... и 4.x из оглавления."""
    to_remove = []
    body = doc.element.body
    for child in body.iterchildren():
        if child.tag != qn("w:p"):
            continue
        text = "".join(child.itertext()).strip()
        # Грубо: TOC-записи, начинающиеся с "4 " или "4."
        if not text:
            continue
        # Проверяем стиль абзаца
        pPr = child.find(qn("w:pPr"))
        if pPr is None:
            continue
        pStyle = pPr.find(qn("w:pStyle"))
        if pStyle is None:
            continue
        style_val = pStyle.get(qn("w:val")) or ""
        if "TOC" not in style_val:
            continue
        if text.startswith("4 ") or text.startswith("4."):
            to_remove.append(child)
    for child in to_remove:
        body.remove(child)


